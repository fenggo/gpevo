"""Python equivalent of SoftModeMutation_310.m (soft displacement fallback operator)."""
from __future__ import annotations

import numpy as np

from gpevo.runtime import G
from gpevo.FunctionFolder.USPEX.src.variation_common import (
    copy_individual, finalize_offspring, pick_parent, valid_molecules,
)
from gpevo.log_utils import console_print


def SoftModeMutation_310(count):
    _ = count
    POP = G["POP_STRUC"]
    scale = getattr(G["ORG_STRUC"], "softStepScale", 1.0)
    for _ in range(50):
        idx = pick_parent()
        if idx is None or idx >= len(POP.POPULATION):
            continue
        child = copy_individual(POP.POPULATION[idx])
        for mol in child.MOLECULES:
            displacement = (np.random.rand(3) - 0.5) * 0.2 * scale
            mol.MOLCOORS = np.asarray(mol.MOLCOORS) + displacement
            mol.MOLCENTER = np.mean(np.asarray(mol.MOLCOORS, dtype=float), axis=0)
        if not valid_molecules(child, -0.1):
            continue
        finalize_offspring(child, "softmutate")
        G["OFF_STRUC"].POPULATION.append(child)
        console_print(f"Structure {count}  generated by SoftModeMutation")
        return
    console_print("failed to do SoftModeMutation in 50 attempts, switch to Random")
    from importlib import import_module as _im
    _im("gpevo.FunctionFolder.USPEX.310.Random_310").Random_310(count)

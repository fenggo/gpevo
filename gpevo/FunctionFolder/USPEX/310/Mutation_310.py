"""Python equivalent of Mutation_310.m (coordinate mutation fallback).

Called by ``SoftModeMutation_310`` when no soft mode is available or every
trial displacement fails ``newMolCheck``.  Ports ``Mutation_310.m``:

* lattice mutation + ``latticeCheck`` (unless ``constLattice``),
* ``move_all_mol_Mutation`` for order-weighted random centre displacements,
* ``newMolCheck(minDistMatrice)`` gating, ``howCome = 'CoorMutate'``.
"""
from __future__ import annotations

import numpy as np

from gpevo.runtime import G, AttrDict
from gpevo.FunctionFolder.USPEX.src.variation_common import (
    copy_individual, finalize_offspring, pick_parent, valid_molecules,
)
from gpevo.FunctionFolder.USPEX.src.softmode import lattice_mutation, move_all_mol_mutation
from gpevo.FunctionFolder.USPEX.src.NEW_coord2Zmatrix import NEW_coord2Zmatrix
from gpevo.FunctionFolder.sys.latticeCheck import latticeCheck
from gpevo.log_utils import console_print


def Mutation_310(count):
    ORG = G["ORG_STRUC"]
    POP = G["POP_STRUC"]
    stdmol = ORG.STDMOL
    const_lattice = int(getattr(ORG, "constLattice", 0))
    mutation_rate = float(getattr(ORG, "mutationRate", 0.08) or 0.08)
    how_many_mut = float(getattr(ORG, "howManyMut", 3) or 3)

    for _ in range(50):
        idx = pick_parent()
        if idx is None or idx >= len(POP.POPULATION):
            continue
        parent = POP.POPULATION[idx]
        molecules = parent.MOLECULES
        lattice = np.asarray(parent.LATTICE, dtype=float).reshape(3, 3)
        mtype_list = [int(v) for v in parent.MtypeLIST]
        num_ions = [int(v) for v in parent.numIons]
        num_mols = [int(v) for v in parent.numMols]
        types_a_list = list(parent.typesAList)

        if not const_lattice:
            mut_lat, _ = lattice_mutation(lattice, mutation_rate)
            if not latticeCheck(mut_lat):
                mut_lat = lattice
                if not latticeCheck(mut_lat):
                    continue
        else:
            mut_lat = np.asarray(getattr(ORG, "lattice", lattice), dtype=float).reshape(3, 3)

        try:
            order = [float(getattr(mol, "order", 0) or 0) for mol in molecules[:len(mtype_list)]]
            order += [0.0] * (len(mtype_list) - len(order))
            frac = move_all_mol_mutation(molecules, num_mols, lattice, order, how_many_mut)
            abs_coord = frac @ mut_lat
        except Exception:
            continue

        child = copy_individual(parent)
        new_molecules = []
        for j, mol in enumerate(molecules[:len(mtype_list)]):
            displacement = abs_coord[j] - np.asarray(mol.ZMATRIX[0], dtype=float)
            clone = copy_individual_mol(mol)
            coords = np.asarray(mol.MOLCOORS, dtype=float) + displacement
            clone.MOLCOORS = coords
            clone.MOLCENTER = np.mean(coords, axis=0)
            clone.ZMATRIX = np.real(NEW_coord2Zmatrix(coords, stdmol[mtype_list[j] - 1].format))
            new_molecules.append(clone)
        child.MOLECULES = new_molecules
        child.LATTICE = mut_lat
        child.numIons = num_ions
        child.numMols = num_mols
        child.MtypeLIST = mtype_list
        child.typesAList = types_a_list

        if not valid_molecules(child, 0):
            continue
        child.Parents = [AttrDict(
            parent=str(getattr(parent, "Number", "")),
            enthalpy=float(np.asarray(parent.Enthalpies, dtype=float).ravel()[-1]),
            N_Moved=int(sum(num_mols)),
        )]
        finalize_offspring(child, "CoorMutate")
        G["OFF_STRUC"].POPULATION.append(child)
        console_print(f"Structure {count}  generated by mutation")
        return

    from importlib import import_module as _im
    _im("gpevo.FunctionFolder.USPEX.310.Random_310").Random_310(count)


def copy_individual_mol(mol):
    import copy
    return copy.copy(mol)
